const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

async function main() {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const events = [], errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('response', (response) => {
      if (response.url().includes('/api/v1/')) events.push({ method: response.request().method(), route: new URL(response.url()).pathname, status: response.status() });
    });
    const out = path.join(__dirname, '../.impeccable/redesign/automated');
    fs.mkdirSync(out, { recursive: true });
    await page.goto(process.env.DEMO_URL || 'http://127.0.0.1:3000/', { waitUntil: 'networkidle' });
    await page.locator('#recipe-list a').first().waitFor();
    assert.equal(await page.locator('.demo-notice, .project-note, #storage-notice, #system-status').count(), 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(out, 'desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile must not overflow');
    await page.screenshot({ path: path.join(out, 'mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('link', { name: 'เพิ่มสูตร', exact: true }).click();
    assert.equal(await page.locator('#create-fields').isDisabled(), true, 'signed out cannot write');
    await page.locator('#create-auth a').click();
    await page.locator('#username').fill('chef_somchai');
    await page.locator('#password').fill('not-the-fixture-password');
    await page.locator('#login-submit').click();
    await page.locator('#login-status.error').waitFor();
    await page.locator('#password').fill(process.env.DEMO_PASSWORD || 'DemoRecipe67160003!');
    await page.locator('#login-submit').click();
    await page.locator('#create:not([hidden])').waitFor();
    assert.equal(await page.locator('#password').inputValue(), '', 'password is cleared after login');
    assert.equal(await page.locator('#create-fields').isDisabled(), false);
    await page.locator('#save-recipe').click();
    assert.equal(await page.locator('#name').evaluate((input) => input.validity.valueMissing), true);
    const name = `สูตรทดสอบ ${Date.now()}`;
    await page.locator('#name').fill(name);
    await page.locator('#category').selectOption('1');
    await page.locator('#minutes').fill('8');
    await page.locator('#steps').fill('ตีไข่ ใส่ต้นหอม ทอดให้สุก เสิร์ฟกับข้าวสวย');
    await page.locator('#save-recipe').click();
    await page.locator('#recipe-success').getByText(`บันทึก "${name}" สำเร็จ`, { exact: false }).waitFor();
    assert.equal(await page.locator('#detail-heading').innerText(), name);
    await page.locator('#score').selectOption('5');
    await page.locator('#review').fill('ทำตามได้ง่าย ใช้เวลาไม่นาน');
    await page.locator('#rating-form button').click();
    await page.getByText('บันทึกคะแนนสำเร็จ คะแนนด้านบนอัปเดตจาก API แล้ว').waitFor();
    assert.match(await page.locator('#rating-summary').innerText(), /5\/5 จาก 1 รีวิว/);
    await page.locator('#score').selectOption('4');
    await page.locator('#rating-form button').click();
    await page.locator('#rating-status.error').waitFor();
    assert.match(await page.locator('#rating-status').innerText(), /รีวิวสูตรอาหารนี้ไปแล้ว/);
    await page.screenshot({ path: path.join(out, 'demo-result.png'), fullPage: true });
    await page.locator('#logout').click();
    assert.equal(await page.locator('#rating-fields').isDisabled(), true);
    await page.getByRole('link', { name: 'สูตรอาหาร', exact: true }).click();
    await page.locator('#recipe-search').fill(name);
    await page.getByRole('link', { name: `ดูสูตร ${name}`, exact: true }).waitFor();
    assert.equal(await page.locator('#recipe-list li').count(), 1);
    await page.locator('#recipe-search').fill('ไม่มีสูตรชื่อนี้แน่นอนxyz');
    await page.getByText('ยังไม่เจอสูตรที่คุณหา', { exact: true }).waitFor();
    await page.locator('#recipe-search').fill('');
    await page.locator('#recipe-sort').selectOption('cook_time_asc');
    await page.locator('#recipe-list a').first().waitFor();
    await page.getByRole('link', { name: 'ไอเดียเมนู', exact: true }).click();
    await page.locator('#ingredient').fill('chicken_breast');
    await page.locator('#ideas-form button').click();
    await page.waitForFunction(() => !document.querySelector('#ideas-form button').disabled);
    assert.ok(await page.locator('#ideas-status').innerText());
    await page.getByRole('link', { name: 'สูตรอาหาร', exact: true }).click();
    await context.setOffline(true);
    await page.locator('#reload').click();
    await page.locator('#list-status.error').waitFor();
    assert.match(await page.locator('#list-status').innerText(), /เชื่อมต่อ API ไม่ได้/);
    await context.setOffline(false);
    await page.locator('#reload').click();
    await page.locator('#recipe-list a').first().waitFor();
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.locator('#login-link').isVisible(), true, 'refresh has no saved token');
    assert.deepEqual(errors, []);
    const report = { result: 'PASS', createdRecipe: name, checks: ['desktop 1440px and mobile 390px no overflow', 'signed-out create guard', 'invalid login exposes 401', 'login clears password and unlocks chef form', 'required name prevents submission', 'POST recipe opens detail', 'POST rating updates average', 'duplicate rating exposes 409', 'logout disables writes', 'server-side full-list search and empty state', 'sort control', 'external result or marked fallback', 'offline error and recovery', 'memory-only session', 'no uncaught browser errors'], events, errors };
    fs.writeFileSync(path.join(__dirname, '../.transaction/ui-browser-automation.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
